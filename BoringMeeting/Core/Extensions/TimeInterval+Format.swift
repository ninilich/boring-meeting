import Foundation

extension TimeInterval {
    func formattedTime() -> String {
        let total = max(0, Int(self))
        let h = total / 3600
        let m = (total % 3600) / 60
        let s = total % 60
        return h > 0
            ? String(format: "%d:%02d:%02d", h, m, s)
            : String(format: "%02d:%02d", m, s)
    }
}
